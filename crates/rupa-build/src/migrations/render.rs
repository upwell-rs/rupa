use rupa_migrate::{Policy, VersionScheme};

use super::Error;
use super::discover::{Artifact, Body};
use super::kind::Kind;

/// Appends one formatted line of generated source.
macro_rules! emit {
    ($out:expr, $($arg:tt)*) => {{
        $out.push_str(&format!($($arg)*));
        $out.push('\n');
    }};
}

/// Path alias `include_migrations!` binds to the runtime crate before including the output.
const RUNTIME: &str = "__rupa_migrate";

/// Renders the generated catalog module body for `artifacts`, in version order.
pub(super) fn catalog(
    stream: &str,
    scheme: VersionScheme,
    artifacts: &[Artifact],
) -> Result<String, Error> {
    let mut out = String::new();
    let scheme = match scheme {
        VersionScheme::Numbered => "Numbered",
        VersionScheme::UtcTimestamp => "UtcTimestamp",
    };

    emit!(
        out,
        "// @generated by rupa-build from the `{stream}` migration directory.\n"
    );
    emit!(out, "/// Stream identity recorded in migration history.");
    emit!(out, "pub const STREAM: &str = {stream:?};\n");
    emit!(
        out,
        "/// Grammar of every file name version in this catalog."
    );
    emit!(
        out,
        "pub const SCHEME: {RUNTIME}::VersionScheme = {RUNTIME}::VersionScheme::{scheme};\n"
    );

    for artifact in artifacts {
        artifact_module(&mut out, artifact)?;
    }

    emit!(out, "{RUNTIME}::migration_catalog! {{");
    emit!(out, "    /// Every migration discovered in this stream.");
    emit!(out, "    pub enum Migrations, error MigrationsError {{");

    for artifact in artifacts {
        emit!(
            out,
            "        {}({}),",
            variant(artifact),
            entry_type(artifact)
        );
    }

    emit!(out, "    }}\n}}\n");
    emit!(out, "/// Catalog members in version order.");
    emit!(out, "pub const ENTRIES: &[Migrations] = &[");

    for artifact in artifacts {
        let value = match &artifact.body {
            Body::Sql { .. }
            | Body::Rust {
                kind: Kind { planned: true, .. },
                ..
            } => {
                format!("{RUNTIME}::Planned({})", type_path(artifact))
            }
            Body::Rust { .. } => type_path(artifact),
        };

        emit!(out, "    Migrations::{}({value}),", variant(artifact));
    }

    emit!(out, "];\n");
    emit!(
        out,
        "/// Validates this catalog without database IO or running migration code."
    );
    emit!(
        out,
        "pub fn catalog() -> ::std::result::Result<{RUNTIME}::Catalog<'static, Migrations>, {RUNTIME}::ValidationError> {{"
    );
    emit!(out, "    {RUNTIME}::Catalog::new(STREAM, SCHEME, ENTRIES)");
    emit!(out, "}}");

    Ok(out)
}

fn artifact_module(out: &mut String, artifact: &Artifact) -> Result<(), Error> {
    let module = module(artifact);
    let name = pascal(&artifact.name);
    let description = &artifact.description;

    match &artifact.body {
        Body::Sql { up, down } => {
            let runtime = format!("super::{RUNTIME}");
            let mut inputs = format!("{runtime}::ArtifactInput::new({:?}, SQL)", up.path);

            emit!(out, "#[doc = {description:?}]");
            emit!(out, "pub mod {module} {{");
            emit!(out, "    #[doc = {description:?}]");
            emit!(out, "    #[derive(Debug, Clone, Copy)]");
            emit!(out, "    pub struct {name};\n");
            emit!(out, "    const SQL: &str = {:?};\n", up.contents);

            if let Some(down) = down {
                inputs.push_str(&format!(
                    ", {runtime}::ArtifactInput::new({:?}, DOWN)",
                    down.path
                ));
                emit!(out, "    const DOWN: &str = {:?};\n", down.contents);
            }

            let mut block = String::new();

            info(&mut block, &runtime, &name, artifact, &inputs, false);

            for line in block.lines() {
                match line {
                    "" => out.push('\n'),
                    line => emit!(out, "    {line}"),
                }
            }

            emit!(out, "    impl {runtime}::PlannedMigration for {name} {{");
            emit!(out, "        fn plan(&self) -> {runtime}::Plan {{");
            emit!(out, "            {runtime}::Plan::new().sql(SQL)");
            emit!(out, "        }}");

            if down.is_some() {
                emit!(out, "");
                emit!(
                    out,
                    "        fn down(&self) -> ::std::option::Option<{runtime}::Plan> {{"
                );
                emit!(
                    out,
                    "            ::std::option::Option::Some({runtime}::Plan::new().sql(DOWN))"
                );
                emit!(out, "        }}");
            }

            emit!(out, "    }}\n}}\n");
        }
        Body::Rust {
            module: path,
            inputs,
            kind,
        } => {
            let path = path.to_str().ok_or_else(|| Error::Utf8(path.clone()))?;
            let inputs = inputs
                .iter()
                .map(|i| {
                    format!(
                        "{RUNTIME}::ArtifactInput::new({:?}, {:?})",
                        i.path, i.contents
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");

            if !artifact.documented {
                emit!(out, "#[doc = {description:?}]");
            }

            emit!(out, "#[path = {path:?}]");
            emit!(out, "pub mod {module};\n");
            info(
                out,
                RUNTIME,
                &type_path(artifact),
                artifact,
                &inputs,
                kind.down,
            );
        }
    }

    Ok(())
}

/// The `MigrationInfo` impl; `imperative_down` declares a scripted
/// migration's `down` body.
fn info(
    out: &mut String,
    runtime: &str,
    name: &str,
    artifact: &Artifact,
    inputs: &str,
    imperative_down: bool,
) {
    emit!(out, "impl {runtime}::MigrationInfo for {name} {{");
    emit!(out, "    fn info(&self) -> &'static {runtime}::Metadata {{");
    emit!(
        out,
        "        const INFO: {runtime}::Metadata = {runtime}::Metadata {{"
    );
    emit!(
        out,
        "            version: {:?},",
        artifact.version.to_string()
    );
    emit!(out, "            description: {:?},", artifact.description);
    emit!(
        out,
        "            policy: {runtime}::Policy::{},",
        policy(artifact.policy)
    );
    emit!(
        out,
        "            kind: {runtime}::MigrationKind::Incremental,"
    );
    emit!(out, "            inputs: &[{inputs}],");
    emit!(out, "        }};\n");
    emit!(out, "        &INFO");
    emit!(out, "    }}");

    if imperative_down {
        emit!(out, "");
        emit!(out, "    fn reversal(&self) -> {runtime}::Reversal {{");
        emit!(out, "        {runtime}::Reversal::Imperative");
        emit!(out, "    }}");
    }

    emit!(out, "}}\n");
}

fn policy(policy: Policy) -> &'static str {
    match policy {
        Policy::TransactionalRequired => "TransactionalRequired",
        Policy::NonTransactional => "NonTransactional",
    }
}

fn module(artifact: &Artifact) -> String {
    format!("m{}_{}", artifact.version, artifact.name)
}

fn variant(artifact: &Artifact) -> String {
    format!("V{}{}", artifact.version, pascal(&artifact.name))
}

fn type_path(artifact: &Artifact) -> String {
    format!("{}::{}", module(artifact), pascal(&artifact.name))
}

fn entry_type(artifact: &Artifact) -> String {
    match &artifact.body {
        Body::Sql { .. }
        | Body::Rust {
            kind: Kind { planned: true, .. },
            ..
        } => {
            format!("{RUNTIME}::Planned<{}>", type_path(artifact))
        }
        Body::Rust { .. } => type_path(artifact),
    }
}

/// Converts a validated snake_case migration name to the PascalCase type name.
pub(super) fn pascal(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().map(|c| c.to_ascii_uppercase());

            first.into_iter().chain(chars).collect::<String>()
        })
        .collect()
}
