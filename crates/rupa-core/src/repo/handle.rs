//! One handle implementation for owned and borrowed repository contexts.

use std::fmt;
use std::marker::PhantomData;

/// Sync queries acquired through a shared source.
#[doc(hidden)]
pub struct SyncMode;

/// Sync queries through an exclusively borrowed executor.
#[doc(hidden)]
pub struct ExclusiveSyncMode;

/// Async queries acquired through a shared source.
#[cfg(feature = "async")]
#[doc(hidden)]
pub struct AsyncMode;

/// Async queries through an exclusively borrowed executor.
#[cfg(feature = "async")]
#[doc(hidden)]
pub struct ExclusiveAsyncMode;

/// Storage for an owned repository source.
#[derive(Debug, Clone, Default)]
#[doc(hidden)]
pub struct Owned<S>(S);

/// Access to a repository's source without changing its ownership.
#[doc(hidden)]
pub trait Context {
    /// The native connection source or executor.
    type Source;

    /// Borrows the source.
    fn as_source(&self) -> &Self::Source;
}

/// Exclusive access to a repository's source.
#[doc(hidden)]
pub trait ContextMut: Context {
    /// Borrows the source exclusively.
    fn as_source_mut(&mut self) -> &mut Self::Source;
}

impl<S> Context for Owned<S> {
    type Source = S;

    fn as_source(&self) -> &S {
        &self.0
    }
}

impl<S> ContextMut for Owned<S> {
    fn as_source_mut(&mut self) -> &mut S {
        &mut self.0
    }
}

impl<S> Context for &S {
    type Source = S;

    fn as_source(&self) -> &S {
        self
    }
}

impl<S> Context for &mut S {
    type Source = S;

    fn as_source(&self) -> &S {
        self
    }
}

impl<S> ContextMut for &mut S {
    fn as_source_mut(&mut self) -> &mut S {
        self
    }
}

/// A repository handle with identity `K` and statically selected execution `M`.
///
/// Use the aliases generated by `#[repository]` to select the storage and mode.
pub struct Repository<C, K, M> {
    context: C,
    identity: PhantomData<fn() -> (K, M)>,
}

/// An owned repository handle.
pub type Repo<S, K, M = SyncMode> = Repository<Owned<S>, K, M>;

/// A pointer-sized borrowed repository view.
pub type RepoView<'a, K, S, M = SyncMode> = Repository<&'a S, K, M>;

/// An exclusively borrowed repository view with no synchronization wrapper.
pub type RepoMut<'a, K, S, M = ExclusiveSyncMode> = Repository<&'a mut S, K, M>;

impl<S, K, M> Repo<S, K, M> {
    /// Owns the given connection source or executor.
    pub const fn new(source: S) -> Self {
        Self {
            context: Owned(source),
            identity: PhantomData,
        }
    }

    /// Returns the owned source or executor.
    pub fn into_inner(self) -> S {
        self.context.0
    }
}

impl<'a, K, S, M> RepoView<'a, K, S, M> {
    /// Borrows a source without cloning, allocating, or locking.
    pub const fn new(source: &'a S) -> Self {
        Self {
            context: source,
            identity: PhantomData,
        }
    }
}

impl<'a, K, S, M> RepoMut<'a, K, S, M> {
    /// Borrows an executor exclusively without allocating or locking.
    pub const fn new(source: &'a mut S) -> Self {
        Self {
            context: source,
            identity: PhantomData,
        }
    }
}

impl<C: Context, K, M> Repository<C, K, M> {
    /// The native source or executor this repository uses.
    pub fn source(&self) -> &C::Source {
        self.context.as_source()
    }
}

impl<C: ContextMut, K, M> Repository<C, K, M> {
    /// The native source or executor, borrowed exclusively.
    pub fn source_mut(&mut self) -> &mut C::Source {
        self.context.as_source_mut()
    }
}

impl<C: Clone, K, M> Clone for Repository<C, K, M> {
    fn clone(&self) -> Self {
        Self {
            context: self.context.clone(),
            identity: PhantomData,
        }
    }
}

impl<C: fmt::Debug, K, M> fmt::Debug for Repository<C, K, M> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("Repository")
            .field("context", &self.context)
            .finish()
    }
}

impl<C: Copy, K, M> Copy for Repository<C, K, M> {}

impl<C: Default, K, M> Default for Repository<C, K, M> {
    fn default() -> Self {
        Self {
            context: C::default(),
            identity: PhantomData,
        }
    }
}
