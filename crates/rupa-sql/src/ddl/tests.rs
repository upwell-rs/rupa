use rupa_core::schema::{
    BTree, ColumnDefault, ColumnType, CustomType, Gin, Hash, Index, IndexColumn, IndexKind,
    ReferentialAction,
};
use rupa_core::{MySql, Postgres, Reference, Sqlite, Value};

use super::*;

const NOTES: TableRef = TableRef::with_schema("app", "notes");

/// `op` rendered for PostgreSQL, MySQL and SQLite.
fn all(op: &SchemaOp) -> [Result<String, RenderError>; 3] {
    [
        render_schema(op, &Postgres),
        render_schema(op, &MySql),
        render_schema(op, &Sqlite),
    ]
}

fn ok(op: &SchemaOp) -> [String; 3] {
    all(op).map(|sql| sql.expect("renderable on every dialect"))
}

fn notes() -> Table {
    Table::at(NOTES)
        .column(ColumnDef::new("id", ColumnType::BigInt).identity())
        .column(ColumnDef::new("title", ColumnType::VarChar(200)).unique())
        .column(ColumnDef::new("body", ColumnType::Text).nullable())
        .column(
            ColumnDef::new("pinned", ColumnType::Bool)
                .default(ColumnDefault::Value(Value::Bool(false))),
        )
        .column(ColumnDef::new("author_id", ColumnType::BigInt).nullable())
        .primary_key(["id"])
        .foreign_key(
            ForeignKey::new(
                ["author_id"],
                Reference {
                    table: TableRef::with_schema("app", "authors"),
                    columns: &["id"],
                },
            )
            .on_delete(ReferentialAction::SetNull),
        )
}

#[test]
fn create_table_uses_each_dialects_types_identity_and_keys() {
    let [postgres, mysql, sqlite] = ok(&SchemaOp::CreateTable(notes()));

    assert_eq!(
        postgres,
        r#"CREATE TABLE "app"."notes" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "title" VARCHAR(200) NOT NULL UNIQUE, "body" TEXT, "pinned" BOOLEAN NOT NULL DEFAULT FALSE, "author_id" BIGINT, PRIMARY KEY ("id"), FOREIGN KEY ("author_id") REFERENCES "app"."authors" ("id") ON DELETE SET NULL)"#
    );
    assert_eq!(
        mysql,
        "CREATE TABLE `app`.`notes` (`id` BIGINT NOT NULL AUTO_INCREMENT, `title` VARCHAR(200) NOT NULL UNIQUE, `body` LONGTEXT, `pinned` BOOLEAN NOT NULL DEFAULT FALSE, `author_id` BIGINT, PRIMARY KEY (`id`), FOREIGN KEY (`author_id`) REFERENCES `app`.`authors` (`id`) ON DELETE SET NULL)"
    );
    assert_eq!(
        sqlite,
        r#"CREATE TABLE "app"."notes" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "title" TEXT NOT NULL UNIQUE, "body" TEXT, "pinned" INTEGER NOT NULL DEFAULT 0, "author_id" INTEGER, FOREIGN KEY ("author_id") REFERENCES "authors" ("id") ON DELETE SET NULL)"#
    );
}

#[test]
fn every_portable_type_has_a_name_on_every_dialect() {
    let types = [
        ColumnType::Bool,
        ColumnType::SmallInt,
        ColumnType::Int,
        ColumnType::BigInt,
        ColumnType::Real,
        ColumnType::Double,
        ColumnType::Decimal {
            precision: 10,
            scale: 2,
        },
        ColumnType::Text,
        ColumnType::VarChar(8),
        ColumnType::Bytes,
        ColumnType::Uuid,
        ColumnType::Date,
        ColumnType::Time,
        ColumnType::Timestamp,
        ColumnType::TimestampTz,
        ColumnType::Json,
    ];
    let table = types
        .iter()
        .enumerate()
        .fold(Table::named("types"), |table, (i, ty)| {
            let name: &'static str = Box::leak(format!("c{i}").into_boxed_str());

            table.column(ColumnDef::new(name, *ty))
        });
    let [postgres, mysql, sqlite] = ok(&SchemaOp::CreateTable(table));

    assert!(
        postgres.contains(r#""c6" NUMERIC(10, 2) NOT NULL"#) && postgres.contains(r#""c15" JSONB"#),
        "{postgres}"
    );
    assert!(
        mysql.contains("`c10` CHAR(36)") && mysql.contains("`c14` DATETIME(6)"),
        "{mysql}"
    );
    assert!(
        sqlite.contains(r#""c9" BLOB"#) && sqlite.contains(r#""c15" TEXT"#),
        "{sqlite}"
    );
}

#[test]
fn alterations_follow_each_dialects_grammar() {
    let cases = [
        (
            SchemaOp::RenameTable {
                table: NOTES,
                to: "posts",
            },
            [
                r#"ALTER TABLE "app"."notes" RENAME TO "posts""#,
                "ALTER TABLE `app`.`notes` RENAME TO `app`.`posts`",
                r#"ALTER TABLE "app"."notes" RENAME TO "posts""#,
            ],
        ),
        (
            SchemaOp::AddColumn {
                table: NOTES,
                column: ColumnDef::new("slug", ColumnType::Text).nullable(),
            },
            [
                r#"ALTER TABLE "app"."notes" ADD COLUMN "slug" TEXT"#,
                "ALTER TABLE `app`.`notes` ADD COLUMN `slug` LONGTEXT",
                r#"ALTER TABLE "app"."notes" ADD COLUMN "slug" TEXT"#,
            ],
        ),
        (
            SchemaOp::RenameColumn {
                table: NOTES,
                from: "body",
                to: "text",
            },
            [
                r#"ALTER TABLE "app"."notes" RENAME COLUMN "body" TO "text""#,
                "ALTER TABLE `app`.`notes` RENAME COLUMN `body` TO `text`",
                r#"ALTER TABLE "app"."notes" RENAME COLUMN "body" TO "text""#,
            ],
        ),
        (
            SchemaOp::DropColumn {
                table: NOTES,
                column: "body",
            },
            [
                r#"ALTER TABLE "app"."notes" DROP COLUMN "body""#,
                "ALTER TABLE `app`.`notes` DROP COLUMN `body`",
                r#"ALTER TABLE "app"."notes" DROP COLUMN "body""#,
            ],
        ),
        (
            SchemaOp::CreateIndex(
                index(
                    "notes_title",
                    BTree::METHOD,
                    [
                        ("title", ColumnType::VarChar(80)),
                        ("id", ColumnType::BigInt),
                    ],
                )
                .unique(),
            ),
            [
                r#"CREATE UNIQUE INDEX "notes_title" ON "app"."notes" ("title", "id")"#,
                "CREATE UNIQUE INDEX `notes_title` ON `app`.`notes` (`title`, `id`)",
                r#"CREATE UNIQUE INDEX "app"."notes_title" ON "notes" ("title", "id")"#,
            ],
        ),
        (
            SchemaOp::DropIndex {
                table: NOTES,
                name: "notes_title",
            },
            [
                r#"DROP INDEX "app"."notes_title""#,
                "DROP INDEX `notes_title` ON `app`.`notes`",
                r#"DROP INDEX "app"."notes_title""#,
            ],
        ),
        (
            SchemaOp::DropTable(NOTES),
            [
                r#"DROP TABLE "app"."notes""#,
                "DROP TABLE `app`.`notes`",
                r#"DROP TABLE "app"."notes""#,
            ],
        ),
    ];

    for (op, expected) in cases {
        assert_eq!(ok(&op), expected, "{op:?}");
    }
}

#[test]
fn defaults_are_checked_literals_or_parenthesized_expressions() {
    let column = |ty, default| SchemaOp::AddColumn {
        table: NOTES,
        column: ColumnDef::new("c", ty).default(default),
    };
    let [postgres, mysql, sqlite] = ok(&column(
        ColumnType::Text,
        ColumnDefault::Value(Value::Text("it's".into())),
    ));
    let [timestamp, ..] = ok(&column(
        ColumnType::TimestampTz,
        ColumnDefault::Sql("CURRENT_TIMESTAMP"),
    ));

    assert!(
        postgres.ends_with(r#""c" TEXT NOT NULL DEFAULT 'it''s'"#),
        "{postgres}"
    );
    assert!(
        mysql.ends_with("`c` LONGTEXT NOT NULL DEFAULT ('it''s')"),
        "{mysql}"
    );
    assert!(
        sqlite.ends_with(r#""c" TEXT NOT NULL DEFAULT 'it''s'"#),
        "{sqlite}"
    );
    assert!(
        timestamp.ends_with("DEFAULT (CURRENT_TIMESTAMP)"),
        "{timestamp}"
    );
    assert!(
        render_schema(
            &column(
                ColumnType::Text,
                ColumnDefault::Value(Value::Text("a\\b'c".into()))
            ),
            &Postgres
        )
        .expect("an escape string")
        .ends_with(r"DEFAULT E'a\\b''c'"),
        "PostgreSQL backslashes mean the same whatever standard_conforming_strings is"
    );
    assert_eq!(
        render_schema(
            &column(
                ColumnType::Text,
                ColumnDefault::Value(Value::Text("a\\b".into()))
            ),
            &MySql
        ),
        Err(RenderError::Schema(Box::new(SchemaError::Default {
            column: "c",
            dialect: DialectId::MySql
        })))
    );
}

#[test]
fn what_a_dialect_cannot_express_is_rejected() {
    let unique_text = Table::named("t").column(ColumnDef::new("name", ColumnType::Text).unique());
    let composite_identity = Table::named("t")
        .column(ColumnDef::new("id", ColumnType::BigInt).identity())
        .column(ColumnDef::new("v", ColumnType::Int))
        .primary_key(["id", "v"]);
    let custom = Table::named("t").column(ColumnDef::new(
        "c",
        ColumnType::Custom(CustomType::new().postgres("CITEXT")),
    ));
    let generated = Table::named("t").column(ColumnDef {
        generated: Some(Generated::Database),
        ..ColumnDef::new("v", ColumnType::Int)
    });
    let cases: [(SchemaOp, &dyn Dialect, SchemaError); 7] = [
        (
            SchemaOp::CreateTable(unique_text),
            &MySql,
            SchemaError::Unindexable {
                column: "name",
                ty: ColumnType::Text,
                dialect: DialectId::MySql,
            },
        ),
        (
            SchemaOp::CreateTable(composite_identity),
            &Sqlite,
            SchemaError::IdentityKey("id"),
        ),
        (
            SchemaOp::CreateTable(custom),
            &Sqlite,
            SchemaError::CustomType {
                column: "c",
                dialect: DialectId::Sqlite,
            },
        ),
        (
            SchemaOp::CreateTable(generated),
            &Postgres,
            SchemaError::MissingDefault("v"),
        ),
        (
            SchemaOp::AddColumn {
                table: NOTES,
                column: ColumnDef::new("slug", ColumnType::Text),
            },
            &Sqlite,
            SchemaError::AddColumn {
                column: "slug",
                dialect: DialectId::Sqlite,
                reason: "a NOT NULL column needs a default",
            },
        ),
        (
            SchemaOp::CreateTable(Table::named("t").primary_key(["id"])),
            &Postgres,
            SchemaError::NoColumns("t"),
        ),
        (
            SchemaOp::CreateIndex(index("empty", BTree::METHOD, [])),
            &Postgres,
            SchemaError::EmptyIndex("empty"),
        ),
    ];

    for (op, dialect, expected) in cases {
        assert_eq!(
            render_schema(&op, dialect),
            Err(RenderError::Schema(Box::new(expected))),
            "{op:?}"
        );
    }
}

#[test]
fn sqlite_foreign_keys_stay_within_their_database() {
    let table = Table::at(NOTES)
        .column(ColumnDef::new("author_id", ColumnType::BigInt))
        .foreign_key(ForeignKey::new(
            ["author_id"],
            Reference {
                table: TableRef::with_schema("other", "authors"),
                columns: &["id"],
            },
        ));

    assert_eq!(
        render_schema(&SchemaOp::CreateTable(table), &Sqlite),
        Err(RenderError::Schema(Box::new(
            SchemaError::CrossSchemaReference("notes")
        )))
    );
}

fn index<const N: usize>(
    name: &'static str,
    kind: rupa_core::schema::IndexMethod,
    columns: [(&'static str, ColumnType); N],
) -> Index {
    Index::new(
        name,
        NOTES,
        columns.map(|(name, ty)| IndexColumn::new(name, ty)),
    )
    .method(kind)
}

fn refusal(index: &'static str, dialect: DialectId, reason: IndexRefusal) -> RenderError {
    RenderError::Schema(Box::new(SchemaError::Index {
        index,
        dialect,
        reason,
    }))
}

#[test]
fn index_kinds_render_their_method_where_supported() {
    let gin = index("notes_doc", Gin::METHOD, [("doc", ColumnType::Json)]);
    let hash = index("notes_slug", Hash::METHOD, [("slug", ColumnType::Text)]);

    assert_eq!(
        render_schema(&SchemaOp::CreateIndex(gin), &Postgres).as_deref(),
        Ok(r#"CREATE INDEX "notes_doc" ON "app"."notes" USING gin ("doc")"#)
    );
    assert_eq!(
        render_schema(&SchemaOp::CreateIndex(hash), &Postgres).as_deref(),
        Ok(r#"CREATE INDEX "notes_slug" ON "app"."notes" USING hash ("slug")"#)
    );
}

#[test]
fn unsupported_kinds_are_refused_with_a_typed_error() {
    let gin = index("notes_doc", Gin::METHOD, [("doc", ColumnType::Json)]);
    let hash = index("notes_slug", Hash::METHOD, [("slug", ColumnType::Text)]);

    for (index, dialect, id, kind, reason) in [
        (
            &gin,
            &MySql as &dyn Dialect,
            DialectId::MySql,
            "gin",
            "MySQL has no GIN indexes",
        ),
        (
            &gin,
            &Sqlite,
            DialectId::Sqlite,
            "gin",
            "SQLite has no GIN indexes",
        ),
        (
            &hash,
            &MySql,
            DialectId::MySql,
            "hash",
            "InnoDB has no hash indexes",
        ),
    ] {
        assert_eq!(
            render_schema(&SchemaOp::CreateIndex(index.clone()), dialect),
            Err(refusal(index.name, id, IndexRefusal::Kind { kind, reason }))
        );
    }
}

#[test]
fn kind_limits_are_checked_at_render() {
    let unique_gin = index("a", Gin::METHOD, [("doc", ColumnType::Json)]).unique();
    let wide_hash = index(
        "b",
        Hash::METHOD,
        [("x", ColumnType::Int), ("y", ColumnType::Int)],
    );

    assert_eq!(
        render_schema(&SchemaOp::CreateIndex(unique_gin), &Postgres),
        Err(refusal(
            "a",
            DialectId::Postgres,
            IndexRefusal::Unique { kind: "gin" }
        ))
    );
    assert_eq!(
        render_schema(&SchemaOp::CreateIndex(wide_hash), &Postgres),
        Err(refusal(
            "b",
            DialectId::Postgres,
            IndexRefusal::MultiColumn { kind: "hash" }
        ))
    );
}

#[test]
fn mysql_refuses_unbounded_index_columns_but_others_accept_them() {
    for ty in [ColumnType::Text, ColumnType::Bytes, ColumnType::Json] {
        let op = SchemaOp::CreateIndex(index(
            "notes_body",
            BTree::METHOD,
            [("id", ColumnType::BigInt), ("body", ty)],
        ));

        assert_eq!(
            render_schema(&op, &MySql),
            Err(refusal(
                "notes_body",
                DialectId::MySql,
                IndexRefusal::Unbounded { column: "body", ty }
            ))
        );
        assert!(render_schema(&op, &Postgres).is_ok());
        assert!(render_schema(&op, &Sqlite).is_ok());
    }

    let bounded = SchemaOp::CreateIndex(index(
        "notes_body",
        BTree::METHOD,
        [("body", ColumnType::VarChar(255))],
    ));

    assert_eq!(
        render_schema(&bounded, &MySql).as_deref(),
        Ok("CREATE INDEX `notes_body` ON `app`.`notes` (`body`)")
    );
}
