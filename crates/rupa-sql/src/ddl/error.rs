use rupa_core::schema::ColumnType;
use rupa_core::{DialectId, SqlType};

/// A schema operation a dialect cannot express as written. Nothing is
/// approximated: the operation must be changed, or written as SQL.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
#[non_exhaustive]
pub enum SchemaError {
    /// `CREATE TABLE` without columns.
    #[error("table `{0}` has no columns")]
    NoColumns(&'static str),
    /// A `CREATE TABLE` primary or foreign key names a column the table does
    /// not have. Alterations of existing tables carry no column list to
    /// check against; the server rejects those.
    #[error("table `{table}` has no column `{column}`")]
    UnknownColumn {
        /// The table.
        table: &'static str,
        /// The missing column.
        column: &'static str,
    },
    /// A column kind this dialect cannot store.
    #[error("{dialect:?} cannot store column `{column}` of kind {kind}: {reason}")]
    UnsupportedType {
        /// The column.
        column: &'static str,
        /// The kind's name.
        kind: &'static str,
        /// The dialect.
        dialect: DialectId,
        /// Why the dialect lacks it.
        reason: &'static str,
    },
    /// `VarChar(0)` or an impossible decimal.
    #[error("column `{column}` has an invalid type {ty:?}")]
    InvalidType {
        /// The column.
        column: &'static str,
        /// The type.
        ty: ColumnType,
    },
    /// An identity column of a non-integer type, or with a default.
    #[error("identity column `{0}` needs an integer type and no default")]
    IdentityType(&'static str),
    /// An identity column that is not the table's whole primary key.
    #[error("identity column `{0}` must be the table's whole primary key")]
    IdentityKey(&'static str),
    /// More than one identity column in a table.
    #[error("table `{0}` has more than one identity column")]
    SeveralIdentities(&'static str),
    /// A database-generated column without a default to generate it.
    #[error("column `{0}` is generated by the database but has no default")]
    MissingDefault(&'static str),
    /// A default value with no safe literal form on this dialect.
    #[error("the default of column `{column}` cannot be written as a {dialect:?} literal")]
    Default {
        /// The column.
        column: &'static str,
        /// The dialect.
        dialect: DialectId,
    },
    /// A column this dialect cannot add to an existing table.
    #[error("{dialect:?} cannot add column `{column}`: {reason}")]
    AddColumn {
        /// The column.
        column: &'static str,
        /// The dialect.
        dialect: DialectId,
        /// What the dialect requires.
        reason: &'static str,
    },
    /// A primary key or `UNIQUE` column of a type this dialect cannot index
    /// without a length.
    #[error("{dialect:?} cannot use column `{column}` of type {ty:?} in a key; use `VarChar`")]
    Unindexable {
        /// The column.
        column: &'static str,
        /// The type.
        ty: ColumnType,
        /// The dialect.
        dialect: DialectId,
    },
    /// A foreign key whose column count differs from the referenced key's.
    #[error("a foreign key of table `{0}` does not match the referenced key's columns")]
    ForeignKeyArity(&'static str),
    /// A SQLite foreign key into another attached database.
    #[error("SQLite foreign keys of table `{0}` cannot reference another schema")]
    CrossSchemaReference(&'static str),
    /// An index without columns.
    #[error("index `{0}` has no columns")]
    EmptyIndex(&'static str),
    /// An index this dialect cannot build as declared.
    #[error("{dialect:?} cannot build index `{index}`: {reason}")]
    Index {
        /// The index.
        index: &'static str,
        /// The dialect.
        dialect: DialectId,
        /// What the dialect refuses.
        reason: IndexRefusal,
    },
    /// An expression of a schema object that DDL cannot hold.
    #[error("{dialect:?} cannot use the expression of `{object}`: {reason}")]
    Expression {
        /// The schema object (index, constraint) holding the expression.
        object: &'static str,
        /// The dialect.
        dialect: DialectId,
        /// What DDL refuses.
        reason: ExprRefusal,
    },
}

/// Why an expression cannot be written in DDL. DDL mode binds nothing and
/// evaluates nowhere, so only what a schema object may hold is accepted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum ExprRefusal {
    /// A call of an aggregate function.
    #[error("the aggregate `{function}` is not allowed")]
    Aggregate {
        /// The function.
        function: &'static str,
    },
    /// A call of a window function.
    #[error("the window function `{function}` is not allowed")]
    Window {
        /// The function.
        function: &'static str,
    },
    /// A call of a function whose result changes between calls, which no
    /// dialect accepts in an index or constraint. Only well-known built-ins
    /// are recognized; the database refuses the rest.
    #[error("the volatile function `{function}` is not allowed")]
    Volatile {
        /// The function.
        function: &'static str,
    },
    /// A column the indexed table does not have: another table's column, or
    /// a column of a joined source.
    #[error("column `{column}` is not a column of the table")]
    Column {
        /// The column.
        column: &'static str,
    },
    /// A bound value with no safe literal form on the dialect (bytes, UUIDs,
    /// dates and times, non-finite floats, text with a NUL or, on MySQL, a
    /// backslash).
    #[error("a {ty:?} value has no safe literal form")]
    Literal {
        /// The value's type.
        ty: SqlType,
    },
}

/// Why a dialect cannot build an index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum IndexRefusal {
    /// The dialect has no such index kind.
    #[error("the {kind} kind is unsupported: {reason}")]
    Kind {
        /// The kind's name.
        kind: &'static str,
        /// Why the dialect lacks it.
        reason: &'static str,
    },
    /// The kind cannot enforce uniqueness.
    #[error("{kind} indexes cannot be unique")]
    Unique {
        /// The kind's name.
        kind: &'static str,
    },
    /// The kind covers one column only.
    #[error("{kind} indexes cover exactly one column")]
    MultiColumn {
        /// The kind's name.
        kind: &'static str,
    },
    /// A column of a type the dialect cannot index without a length.
    #[error("column `{column}` of type {ty:?} has no length; use `VarChar`")]
    Unbounded {
        /// The column.
        column: &'static str,
        /// The type.
        ty: ColumnType,
    },
    /// An expression whose result type the dialect cannot index without a
    /// length.
    #[error("an expression of type {ty:?} has no length and cannot be indexed")]
    UnboundedExpr {
        /// The expression's result type.
        ty: ColumnType,
    },
    /// The dialect has no partial indexes.
    #[error("the dialect has no partial indexes")]
    Partial,
}
