#[test]
fn create_table_uses_each_dialects_types_identity_and_keys() {
    let [postgres, mysql, sqlite] = ok(&SchemaOp::CreateTable(notes()));

    assert_eq!(
        postgres,
        r#"CREATE TABLE "app"."notes" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "title" VARCHAR(200) NOT NULL UNIQUE, "body" TEXT, "pinned" BOOLEAN NOT NULL DEFAULT FALSE, "author_id" BIGINT, PRIMARY KEY ("id"), FOREIGN KEY ("author_id") REFERENCES "app"."authors" ("id") ON DELETE SET NULL)"#
    );
    assert_eq!(
        mysql,
        "CREATE TABLE `app`.`notes` (`id` BIGINT NOT NULL AUTO_INCREMENT, `title` VARCHAR(200) NOT NULL UNIQUE, `body` LONGTEXT, `pinned` BOOLEAN NOT NULL DEFAULT FALSE, `author_id` BIGINT, PRIMARY KEY (`id`), FOREIGN KEY (`author_id`) REFERENCES `app`.`authors` (`id`) ON DELETE SET NULL)"
    );
    assert_eq!(
        sqlite,
        r#"CREATE TABLE "app"."notes" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "title" TEXT NOT NULL UNIQUE, "body" TEXT, "pinned" INTEGER NOT NULL DEFAULT 0, "author_id" INTEGER, FOREIGN KEY ("author_id") REFERENCES "authors" ("id") ON DELETE SET NULL)"#
    );
}

#[test]
fn every_portable_type_has_a_name_on_every_dialect() {
    let types = [
        ColumnType::Bool,
        ColumnType::SmallInt,
        ColumnType::Int,
        ColumnType::BigInt,
        ColumnType::Real,
        ColumnType::Double,
        ColumnType::Decimal {
            precision: 10,
            scale: 2,
        },
        ColumnType::Text,
        ColumnType::VarChar(8),
        ColumnType::Bytes,
        ColumnType::Uuid,
        ColumnType::Date,
        ColumnType::Time,
        ColumnType::Timestamp,
        ColumnType::TimestampTz,
        ColumnType::Json,
    ];
    let table = types
        .iter()
        .enumerate()
        .fold(Table::named("types"), |table, (i, ty)| {
            let name: &'static str = Box::leak(format!("c{i}").into_boxed_str());

            table.column(ColumnDef::new(name, *ty))
        });
    let [postgres, mysql, sqlite] = ok(&SchemaOp::CreateTable(table));

    assert!(
        postgres.contains(r#""c6" NUMERIC(10, 2) NOT NULL"#) && postgres.contains(r#""c15" JSONB"#),
        "{postgres}"
    );
    assert!(
        mysql.contains("`c10` CHAR(36)") && mysql.contains("`c14` DATETIME(6)"),
        "{mysql}"
    );
    assert!(
        sqlite.contains(r#""c9" BLOB"#) && sqlite.contains(r#""c15" TEXT"#),
        "{sqlite}"
    );
}

#[test]
fn what_a_dialect_cannot_express_is_rejected() {
    let unique_text = Table::named("t").column(ColumnDef::new("name", ColumnType::Text).unique());
    let composite_identity = Table::named("t")
        .column(ColumnDef::new("id", ColumnType::BigInt).identity())
        .column(ColumnDef::new("v", ColumnType::Int))
        .primary_key(["id", "v"]);
    let custom = Table::named("t").column(ColumnDef::new(
        "c",
        ColumnType::Custom(CustomType::new().postgres("CITEXT")),
    ));
    let generated = Table::named("t").column(ColumnDef {
        generated: Some(Generated::Database),
        ..ColumnDef::new("v", ColumnType::Int)
    });
    let cases: [(SchemaOp, &dyn Dialect, SchemaError); 7] = [
        (
            SchemaOp::CreateTable(unique_text),
            &MySql,
            SchemaError::Unindexable {
                column: "name",
                ty: ColumnType::Text,
                dialect: DialectId::MySql,
            },
        ),
        (
            SchemaOp::CreateTable(composite_identity),
            &Sqlite,
            SchemaError::IdentityKey("id"),
        ),
        (
            SchemaOp::CreateTable(custom),
            &Sqlite,
            SchemaError::CustomType {
                column: "c",
                dialect: DialectId::Sqlite,
            },
        ),
        (
            SchemaOp::CreateTable(generated),
            &Postgres,
            SchemaError::MissingDefault("v"),
        ),
        (
            SchemaOp::AddColumn {
                table: NOTES,
                column: ColumnDef::new("slug", ColumnType::Text),
            },
            &Sqlite,
            SchemaError::AddColumn {
                column: "slug",
                dialect: DialectId::Sqlite,
                reason: "a NOT NULL column needs a default",
            },
        ),
        (
            SchemaOp::CreateTable(Table::named("t").primary_key(["id"])),
            &Postgres,
            SchemaError::NoColumns("t"),
        ),
        (
            SchemaOp::CreateIndex(index("empty", BTree::METHOD, [])),
            &Postgres,
            SchemaError::EmptyIndex("empty"),
        ),
    ];

    for (op, dialect, expected) in cases {
        assert_eq!(
            render_schema(&op, dialect),
            Err(RenderError::Schema(Box::new(expected))),
            "{op:?}"
        );
    }
}

#[test]
fn sqlite_foreign_keys_stay_within_their_database() {
    let table = Table::at(NOTES)
        .column(ColumnDef::new("author_id", ColumnType::BigInt))
        .foreign_key(ForeignKey::new(
            ["author_id"],
            Reference {
                table: TableRef::with_schema("other", "authors"),
                columns: &["id"],
            },
        ));

    assert_eq!(
        render_schema(&SchemaOp::CreateTable(table), &Sqlite),
        Err(RenderError::Schema(Box::new(
            SchemaError::CrossSchemaReference("notes")
        )))
    );
}
