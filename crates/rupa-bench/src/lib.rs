//! Shared model and fixtures for the benchmarks in `benches/`.
//!
//! Run them with `cargo bench -p rupa-bench`; see `docs/benchmarks.md` for
//! what each one measures and how to compare against a saved baseline.

use rupa::prelude::*;
use serde::{Deserialize, Serialize};

/// A JSON column.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Prefs {
    pub theme: String,
    pub beta: bool,
}

/// The benchmarked entity: a generated id, text, a nullable column, a flag
/// and a JSON column.
#[derive(Debug, Clone, PartialEq, Entity, Gettable, Insertable, Updatable, Deletable)]
#[entity(table = "users")]
pub struct User {
    #[id(generated)]
    pub id: i64,
    pub email: String,
    pub name: Option<String>,
    pub active: bool,
    pub prefs: Prefs,
}

/// Insert input: no id.
#[derive(Debug, Clone, Insertable)]
#[insertable(entity = User)]
pub struct NewUser {
    pub email: String,
    pub name: Option<String>,
    pub active: bool,
    pub prefs: Prefs,
}

/// A dyn-compatible repository, as an application would inject it.
#[repository]
pub trait Users: Send + Sync {
    #[query(get)]
    async fn by_id(&self, id: i64) -> Result<Option<User>, rupa::DynError>;

    #[query(filter = email == $email)]
    async fn by_email(&self, email: &str) -> Result<Option<User>, rupa::DynError>;

    #[query(filter = active == true, order_by = id, limit = $n)]
    async fn active(&self, n: u64) -> Result<Vec<User>, rupa::DynError>;
}

/// SQLite schema for [`User`].
pub const SQLITE_DDL: &str = "
DROP TABLE IF EXISTS users;
CREATE TABLE users (
    id     INTEGER PRIMARY KEY,
    email  TEXT NOT NULL UNIQUE,
    name   TEXT,
    active INTEGER NOT NULL,
    prefs  TEXT NOT NULL
);";

/// Postgres schema for [`User`].
pub const POSTGRES_DDL: &str = "
DROP TABLE IF EXISTS users;
CREATE TABLE users (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email  text NOT NULL UNIQUE,
    name   text,
    active boolean NOT NULL,
    prefs  jsonb NOT NULL
);";

/// `n` distinct users; every third is inactive.
pub fn new_users(n: usize) -> Vec<NewUser> {
    (0..n)
        .map(|i| NewUser {
            email: format!("user{i}@example.com"),
            name: (i % 2 == 0).then(|| format!("User {i}")),
            active: i % 3 != 0,
            prefs: Prefs {
                theme: if i % 2 == 0 { "dark" } else { "light" }.into(),
                beta: i % 5 == 0,
            },
        })
        .collect()
}
